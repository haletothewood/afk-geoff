import fs from 'node:fs';
import assert from 'node:assert/strict';
import { lifecycleEventSchema } from '/Users/david/Documents/ChatGPT/afk-geoff/packages/shared/dist/index.js';
const root = '/private/tmp/afk-watcher-rerun-2026-10-26';
const lines = fs.readFileSync(`${root}/watch.stdout`, 'utf8').trim().split('\n').map(JSON.parse);
const raw = fs.readFileSync(`${root}/raw-progress.ndjson`, 'utf8').trim().split('\n').map(JSON.parse);
const events = lines.filter(line => line.kind === 'run_event');
for (const event of events) lifecycleEventSchema.parse(event);
const offset = raw.find(progress => progress.updatedAt.endsWith('+00:00'));
assert.ok(offset, 'worker wrote offset timestamp');
assert.ok(events.some(event => event.event === 'progress_observed' && event.progressUpdatedAt === new Date(offset.updatedAt).toISOString()), 'watch observed and normalized the offset timestamp');
assert.equal(lines.filter(line => line.event === 'watch_started').length, 1);
assert.equal(lines.filter(line => line.kind === 'watch_result').length, 1);
assert.equal(lines.at(-1).ok, true);
assert.equal(lines.at(-1).status, 'completed');
const handoff = JSON.parse(fs.readFileSync(`${root}/handoff.stdout`, 'utf8'));
assert.equal(handoff.publishable, true);
assert.equal(handoff.reviewVerdict, 'PASS');
assert.equal(handoff.verificationStatus, 'passed');
assert.equal(handoff.worktreeClean, true);
assert.equal(fs.readFileSync(`${root}/watch.stderr`, 'utf8'), '');
console.log(JSON.stringify({ok:true,lifecycleEvents:events.length,watchInvocations:1,rawOffset:offset.updatedAt,normalizedOffset:new Date(offset.updatedAt).toISOString()}));
